// Generates dist/tailwind.css from the tokens (dist/tokens.ts, generated from dist/tokens.json): every token as a
// Tailwind theme value, so the classes the library builds (`bg-red-500`, `p-4`, `rounded-lg`, `shadow-md`, `text-sm`)
// take the tokens' values; the colors' Light and Dark values as themes; a `@source` for the library's own files; and a
// safelist of every class name a flag can produce (e.g. `bg-red-500` for `fill-red-500`), which Tailwind can't find by
// scanning because the library builds them at runtime. Consumers import the result and need no build step of their
// own. Rerun with `bun run generate:tailwind` after changing the tokens, and commit the result.
import { writeFileSync } from "node:fs"
import {
  CONTAINERS,
  RADIUS,
  SHADOWS,
  SPACING,
  SPACING_TAILWIND,
  type SpacingPixelKey,
  TEXT_SIZES,
  TOKENS,
} from "../dist/tokens"
import { FLAGS, flagClasses } from "../src/maps"

// A theme key with a dot (`0.5`) escapes it, as Tailwind's own theme does.
const key = (name: string) => name.replace(".", "\\.")

const theme = ["  --color-currentcolor: currentColor;", "  --color-transparent: transparent;"]

for (const [name, hex] of Object.entries(TOKENS.colors.Light)) {
  theme.push(`  --color-${name.replace(/^fill-/, "")}: ${hex};`)
}

// `full` is a keyword, not a size: it stays Tailwind's 100% (`w-full`), which is what the library's `width-full` means.
for (const unit of Object.keys(SPACING).filter((unit): unit is SpacingPixelKey => unit !== "full")) {
  theme.push(`  --spacing-${key(SPACING_TAILWIND[unit] ?? unit)}: ${SPACING[unit]}px;`)
}

for (const [name, pixels] of Object.entries(RADIUS)) {
  theme.push(`  --radius-${name}: ${pixels}px;`)
}

for (const [name, pixels] of Object.entries(CONTAINERS)) {
  theme.push(`  --container-${name}: ${pixels}px;`)
}

const shadowTokens = TOKENS.shadows.Default as Record<string, number | string>

for (const name of SHADOWS) {
  const layers: string[] = []

  for (let layer = 1; `shadow-${name}-${layer}-color` in shadowTokens; layer++) {
    const field = (part: string) => shadowTokens[`shadow-${name}-${layer}-${part}`]

    layers.push(
      `${field("offset-x")}px ${field("offset-y")}px ${field("blur")}px ${field("spread")}px ${field("color")}`,
    )
  }

  theme.push(`  --shadow-${name}: ${layers.join(", ")};`)
}

const typography = TOKENS.typography.Default as Record<string, number>

for (const size of TEXT_SIZES) {
  theme.push(`  --text-${size}: ${typography[`font-size-${size}`]}px;`)
  theme.push(`  --text-${size}--line-height: ${typography[`line-height-${size}`]}px;`)
}

for (const [name, weight] of Object.entries(typography)) {
  if (name.startsWith("font-weight-")) theme.push(`  --${name}: ${weight};`)
}

// `@variant light` and `@variant dark` inside a theme layer are the form both Tailwind on web (`prefers-color-scheme`)
// and Uniwind on iOS and Android read as themes. Uniwind requires every theme to declare the same variables, so the
// Light values are repeated under `@variant light` although `@theme` already holds them.
const themeColors = (mode: "Light" | "Dark") =>
  Object.entries(TOKENS.colors[mode]).map(([name, hex]) => `      --color-${name.replace(/^fill-/, "")}: ${hex};`)

const themeCss = [
  "",
  '@source "../src";',
  "",
  "@theme {",
  ...theme,
  "}",
  "",
  // Tailwind has no `light` variant of its own. This is Uniwind's definition, so whichever of the two loads last,
  // `.light` / `.dark` classes and `prefers-color-scheme` behave the same.
  "@custom-variant light {",
  "  &:where(.light, .light *) {",
  "    @slot;",
  "  }",
  "",
  "  @media (prefers-color-scheme: light) {",
  "    &:not(:where(.light, .light *, .dark, .dark *)) {",
  "      @slot;",
  "    }",
  "  }",
  "}",
  "",
  "@layer theme {",
  "  :root {",
  "    @variant light {",
  ...themeColors("Light"),
  "    }",
  "",
  "    @variant dark {",
  ...themeColors("Dark"),
  "    }",
  "  }",
  "}",
  "",
]

writeFileSync(
  new URL("../dist/tailwind.css", import.meta.url),
  [
    "/* Generated by scripts/generateTailwind.ts from the design tokens. Do not edit. */",
    ...themeCss,
    `@source inline("${[...new Set([...FLAGS.values()].flatMap(flagClasses))].join(" ")}");`,
    "",
  ].join("\n"),
)
