// Generates dist/tokens.ts from dist/tokens.json: the same collections, modes and variable names, with each token
// reduced to its value (colors as hex, `#RRGGBBAA` when translucent; numbers as pixels), as one `as const` object the
// components can import with exact types. Rerun with `bun run tokens:ts` after changing tokens.json, and commit the
// result.
import { readFileSync, writeFileSync } from "node:fs"

type Token = { $type: string; $value: unknown }
type Color = { hex: string; alpha: number }

const tokens = JSON.parse(readFileSync(new URL("../dist/tokens.json", import.meta.url), "utf8")) as Record<
  string,
  Record<string, Record<string, Token | unknown>>
>

const tokenValue = (token: Token): string | number | boolean => {
  if (token.$type !== "color") return token.$value as string | number | boolean

  const { hex, alpha } = token.$value as Color
  const suffix =
    alpha < 1
      ? Math.round(alpha * 255)
          .toString(16)
          .padStart(2, "0")
          .toUpperCase()
      : ""

  return `${hex}${suffix}`
}

const lines = [
  "// Generated by scripts/generateTokensTs.ts from dist/tokens.json. Do not edit.",
  "",
  "export const TOKENS = {",
]

for (const [collection, modes] of Object.entries(tokens)) {
  lines.push(`  ${JSON.stringify(collection)}: {`)

  for (const [mode, variables] of Object.entries(modes)) {
    lines.push(`    ${JSON.stringify(mode)}: {`)

    for (const [name, token] of Object.entries(variables)) {
      if (name.startsWith("$")) continue

      lines.push(`      ${JSON.stringify(name)}: ${JSON.stringify(tokenValue(token as Token))},`)
    }

    lines.push("    },")
  }

  lines.push("  },")
}

lines.push("} as const", "", "export type Tokens = typeof TOKENS", "")

writeFileSync(new URL("../dist/tokens.ts", import.meta.url), lines.join("\n"))
