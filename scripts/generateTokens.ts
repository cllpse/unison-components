// Generates dist/design-tokens.ts from dist/design-tokens.json, and is rerun with `bun run generate:tokens` after changing it (commit the
// result). It holds two kinds of export:
//
// - TOKENS: the same collections, modes and variable names, with each token reduced to its value (colors as hex,
//   `#RRGGBBAA` when translucent; numbers as pixels), as one `as const` object consumers can import with exact types.
// - The scales the components and consumers read at runtime, under their public names (COLORS, SPACING, RADIUS,
//   CONTAINERS, SHADOWS, TEXT_SIZES), with the types derived from them. Splitting the names here, rather than at module
//   load, keeps the regex out of the app and gives the types plain literal keys instead of names parsed with `infer`.
//   The components never read TOKENS, so bundlers that drop unused exports leave it, with Dark, shadow layers and
//   typography values, out of the app.
import { readFileSync, writeFileSync } from "node:fs"

type Token = { $type: string; $value: unknown }
type Color = { hex: string; alpha: number }
type Variables = Record<string, Token | unknown>

const tokens = JSON.parse(readFileSync(new URL("../dist/design-tokens.json", import.meta.url), "utf8")) as Record<
  string,
  Record<string, Variables>
>

const tokenValue = (token: Token): string | number | boolean => {
  if (token.$type !== "color") return token.$value as string | number | boolean

  const { hex, alpha } = token.$value as Color
  const suffix =
    alpha < 1
      ? Math.round(alpha * 255)
          .toString(16)
          .padStart(2, "0")
          .toUpperCase()
      : ""

  return `${hex}${suffix}`
}

/** A collection mode's variables as [name, value], without the `$`-prefixed metadata. */
const values = (variables: Variables) =>
  Object.entries(variables)
    .filter(([name]) => !name.startsWith("$"))
    .map(([name, token]) => [name, tokenValue(token as Token)] as const)

const literal = (value: unknown) => JSON.stringify(value)

// dist/design-tokens.ts

const lines = [
  "// Generated by scripts/generateTokens.ts from dist/design-tokens.json. Do not edit.",
  "",
  "export const TOKENS = {",
]

for (const [collection, modes] of Object.entries(tokens)) {
  lines.push(`  ${literal(collection)}: {`)

  for (const [mode, variables] of Object.entries(modes)) {
    lines.push(`    ${literal(mode)}: {`)

    for (const [name, value] of values(variables)) {
      lines.push(`      ${literal(name)}: ${literal(value)},`)
    }

    lines.push("    },")
  }

  lines.push("  },")
}

lines.push("} as const", "", "export type Tokens = typeof TOKENS", "")

// Scales

const fail = (message: string): never => {
  throw new Error(`generateTokens: ${message}`)
}

// `fill-<hue>-<shade>` variables become palettes and `fill-<name>` ones plain colors. Anything else would get a flag
// name the components can't parse, so it stops the build instead.
const palettes: Record<string, Record<string, string>> = {}
const plainColors: Record<string, string> = {}

for (const [name, hex] of values(tokens.colors.Light)) {
  const palette = name.match(/^fill-([a-z]+)-(\d+)$/)
  const plain = name.match(/^fill-([a-z]+)$/)

  if (palette) {
    palettes[palette[1]] ??= {}
    palettes[palette[1]][palette[2]] = String(hex)
  } else if (plain) {
    plainColors[plain[1]] = String(hex)
  } else {
    fail(`color "${name}" is neither fill-<hue>-<shade> nor fill-<name>`)
  }
}

/** The units collection's variables named `<prefix><key>`, as [key, pixels], in the tokens' order. */
const scale = (prefix: string) =>
  values(tokens.units.Default)
    .filter(([name]) => name.startsWith(prefix))
    .map(([name, pixels]) => [name.slice(prefix.length), pixels] as const)

const spacing = scale("spacing-")
const shadows = [...new Set(values(tokens.shadows.Default).map(([name]) => name.split("-")[1]))]
const textSizes = values(tokens.typography.Default)
  .filter(([name]) => name.startsWith("font-size-"))
  .map(([name]) => name.slice("font-size-".length))

const object = (entries: readonly (readonly [string, unknown])[], indent = "  ") =>
  ["{", ...entries.map(([key, value]) => `${indent}${literal(key)}: ${literal(value)},`), `${indent.slice(2)}}`].join(
    "\n",
  )

// The scales under the names the components and consumers use, with their JSDoc, and the types derived from them.
const scales = [
  "/**",
  " * The colors, Light mode: palettes from the colors collection's `fill-<hue>-<shade>` variables and plain colors from",
  " * its `fill-<name>` ones. The Dark values reach only the generated tailwind.css. `currentcolor` and `transparent` are",
  " * CSS keywords, not tokens.",
  ' * @example COLORS.red["500"] // "#FB2C36"',
  " */",
  "export const COLORS = {",
  '  currentcolor: "currentColor",',
  '  transparent: "transparent",',
  ...Object.entries(palettes).map(([hue, shades]) => `  ${literal(hue)}: ${object(Object.entries(shades), "    ")},`),
  ...Object.entries(plainColors).map(([name, hex]) => `  ${literal(name)}: ${literal(hex)},`),
  "} as const",
  "",
  "export type ColorName = keyof typeof COLORS",
  "",
  "export type PaletteColorName = {",
  "  [Name in ColorName]: (typeof COLORS)[Name] extends string ? never : Name",
  "}[ColorName]",
  "",
  "export type PlainColorName = Exclude<ColorName, PaletteColorName>",
  "",
  "export type ColorShade = { [Name in PaletteColorName]: keyof (typeof COLORS)[Name] }[PaletteColorName]",
  "",
  "/** Every color as a flag suffix: `white`, `red-500`. */",
  "export type ColorNameAndShade =",
  "  | PlainColorName",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source text, not a template
  "  | { [Name in PaletteColorName]: `${Name}-${keyof (typeof COLORS)[Name] & string}` }[PaletteColorName]",
  "",
  "/**",
  " * The spacing scale from the units collection's `spacing-` variables, as [key, pixel value]. Keys are the tokens'",
  " * (`spacing-0p5` gives `0p5`); see SPACING_TAILWIND for the Tailwind class suffix. `full` is a keyword, not a size:",
  " * Figma stores it as 999px, and it means 100% (`w-full`); read pixels through SpacingPixelKey to leave it out.",
  ' * @example SPACING["4"] // 16',
  " */",
  `export const SPACING = ${object(spacing)} as const`,
  "",
  "/** The spacing keys that are real pixel sizes, i.e. all but `full`. */",
  'export type SpacingPixelKey = Exclude<keyof typeof SPACING, "full">',
  "",
  "/**",
  " * Tailwind spacing suffixes for keys that differ from their key: fractional keys spell the dot as `p`, which a",
  " * Tailwind class can't use.",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source text, not a template
  ' * @example `p-${SPACING_TAILWIND[key] ?? key}` // "1p5" → "p-1.5", "4" → "p-4"',
  " */",
  `export const SPACING_TAILWIND: Partial<Record<keyof typeof SPACING, string>> = ${object(
    spacing.filter(([key]) => /^\d+p\d+$/.test(key)).map(([key]) => [key, key.replace("p", ".")]),
  )}`,
  "",
  "/**",
  " * The corner radius scale from the units collection's `radius-` variables, as [Tailwind suffix, pixel value]. Radius",
  " * has its own names (`rounded-lg`, not `rounded-2`), so it doesn't share the spacing keys.",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source text, not a template
  ' * @example `rounded-${key}` // "lg" → "rounded-lg" (8px)',
  " */",
  `export const RADIUS = ${object(scale("radius-"))} as const`,
  "",
  "/**",
  " * Tailwind's container scale for widths from the units collection's `container-` variables, as [Tailwind suffix, pixel",
  " * value]: fixed sizes, not percentages.",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source text, not a template
  ' * @example `w-${key}` // "md" → "w-md" (448px)',
  " */",
  `export const CONTAINERS = ${object(scale("container-"))} as const`,
  "",
  "/** The shadow names from the shadows collection (`shadow-md`), in the tokens' order. */",
  `export const SHADOWS = ${literal(shadows)} as const`,
  "",
  "/** The text sizes from the typography collection's `font-size-` variables (`text-sm`), in the tokens' order. */",
  `export const TEXT_SIZES = ${literal(textSizes)} as const`,
  "",
]

if (spacing.length === 0 || shadows.length === 0 || textSizes.length === 0) fail("a scale came out empty")

writeFileSync(new URL("../dist/design-tokens.ts", import.meta.url), [...lines, ...scales].join("\n"))
