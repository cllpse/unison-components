if (spacing.length === 0 || shadows.length === 0 || textSizes.length === 0) fail("a scale came out empty")

// Motion, from dist/motion-tokens.css: the Tailwind theme variables and keyframes the web reads as they are, turned into
// the values iOS and Android need, where Uniwind drops easings and keyframes (see utilities/configureMotion.ts). The
// file only holds custom properties and `@keyframes` inside one `@theme`, so a small parser reads it.

const css = readFileSync(new URL("../dist/motion-tokens.css", import.meta.url), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")

/** The body of every `<prelude> { … }` block directly inside `source`, as [prelude, body]. */
const blocks = (source: string) => {
  const found: [string, string][] = []
  let depth = 0
  let start = 0
  let prelude = ""

  for (let i = 0; i < source.length; i++) {
    if (source[i] === "{") {
      if (depth === 0) {
        prelude = source.slice(source.lastIndexOf("}", i) + 1, i)
        prelude = prelude.slice(prelude.lastIndexOf(";") + 1).trim()
        start = i + 1
      }
      depth++
    } else if (source[i] === "}") {
      depth--
      if (depth === 0) found.push([prelude, source.slice(start, i)])
    }
  }

  return found
}

/** A block's own declarations, as [property, value], skipping nested blocks. */
const declarations = (body: string) => {
  let own = body

  // Innermost blocks first, until none are left.
  while (own.includes("{")) own = own.replace(/[^;{}]*\{[^{}]*\}/g, "")

  return own
    .split(";")
    .map((declaration) => declaration.trim())
    .filter(Boolean)
    .map((declaration) => {
      const colon = declaration.indexOf(":")

      return [
        declaration.slice(0, colon).trim(),
        declaration
          .slice(colon + 1)
          .replace(/\s+/g, " ")
          .trim(),
      ] as const
    })
}

const theme = blocks(css).find(([prelude]) => prelude === "@theme")?.[1] ?? fail("motion-tokens.css has no @theme")
const variables = declarations(theme)

/** The `--<prefix><key>` variables, as [key, value], in the file's order. */
const namespace = (prefix: string) =>
  variables
    .filter(([name]) => name.startsWith(`--${prefix}`))
    .map(([name, value]) => [name.slice(prefix.length + 2), value] as const)

/** An easing as React Native's CSS animations take it: a keyword, or cubic-bezier control points. */
const easing = (value: string): string | number[] => {
  const bezier = value.match(/^cubic-bezier\((.+)\)$/)

  return bezier ? bezier[1].split(",").map(Number) : value
}

const milliseconds = (value: string) =>
  value.endsWith("ms") ? Number.parseFloat(value) : Math.round(Number.parseFloat(value) * 1000)

// CSS properties as React Native style keys. Tailwind's own variables (`--tw-gradient-from`) and SVG's `fill` and
// `stroke`, which React Native styles don't have, are dropped; `translate`, `scale` and `rotate` are all `transform`.
const STYLE_KEYS: Record<string, string | undefined> = {
  color: "color",
  "background-color": "backgroundColor",
  "border-color": "borderColor",
  "outline-color": "outlineColor",
  "text-decoration-color": "textDecorationColor",
  opacity: "opacity",
  "box-shadow": "boxShadow",
  transform: "transform",
  translate: "transform",
  scale: "transform",
  rotate: "transform",
}

const transitionProperties = namespace("transition-property-").map(
  ([key, value]) =>
    [key, [...new Set(value.split(",").flatMap((property) => STYLE_KEYS[property.trim()] ?? []))]] as const,
)

const defaults = Object.fromEntries(variables)

// A keyframe's `transform` as React Native's list (`rotate(360deg)` → `[{ rotate: "360deg" }]`), keeping lengths
// and angles as strings and plain numbers as numbers. `none` is the identity of the functions the other keyframes use,
// so the two ends of the animation have the same shape.
const transform = (value: string, functions: string[]) => {
  if (value === "none") return functions.map((name) => ({ [name]: name.startsWith("scale") ? 1 : 0 }))

  return [...value.matchAll(/([a-zA-Z]+)\(([^)]+)\)/g)].map(([, name, argument]) => ({
    [name]: /^-?[\d.]+$/.test(argument) ? Number(argument) : argument,
  }))
}

const keyframes = Object.fromEntries(
  blocks(theme)
    .filter(([prelude]) => prelude.startsWith("@keyframes "))
    .map(([prelude, body]) => {
      const steps = blocks(body).map(([selector, stepBody]) => [selector, declarations(stepBody)] as const)
      const functions = [
        ...new Set(
          steps.flatMap(([, properties]) =>
            properties
              .filter(([property, value]) => property === "transform" && value !== "none")
              .flatMap(([, value]) => [...value.matchAll(/([a-zA-Z]+)\(/g)].map((match) => match[1])),
          ),
        ),
      ]

      const frames: Record<string, Record<string, unknown>> = {}

      for (const [selector, properties] of steps) {
        const style: Record<string, unknown> = {}

        for (const [property, value] of properties) {
          if (property === "transform") style.transform = transform(value, functions)
          else if (property === "opacity") style.opacity = Number(value)
          else if (property === "animation-timing-function") style.animationTimingFunction = easing(value)
          else fail(`keyframes ${prelude}: "${property}" has no React Native equivalent here`)
        }

        for (const part of selector.split(",")) {
          const offset = part
            .trim()
            .replace(/^from$/, "0%")
            .replace(/^to$/, "100%")

          frames[offset] = { ...frames[offset], ...style }
        }
      }

      const ordered = Object.entries(frames).sort(([a], [b]) => Number.parseFloat(a) - Number.parseFloat(b))

      return [prelude.slice("@keyframes ".length).trim(), Object.fromEntries(ordered)] as const
    }),
)

// `--animate-<name>: <keyframes> <duration> [<easing>] <iteration count>`, the shorthand Tailwind's theme uses.
const animations = namespace("animate-").map(([key, value]) => {
  const parts = value.match(/cubic-bezier\([^)]+\)|\S+/g) ?? []
  const [name = "", duration = "0s", ...rest] = parts
  const iterationCount = rest.at(-1) === "infinite" ? "infinite" : Number(rest.at(-1) ?? 1)
  const timing = rest.length > 1 ? rest[0] : "ease"

  return [
    key,
    {
      duration: milliseconds(duration),
      easing: easing(timing),
      iterationCount,
      keyframes: keyframes[name] ?? fail(`--animate-${key} names keyframes "${name}", which aren't defined`),
    },
  ] as const
})

const durations = namespace("transition-duration-").map(([key, value]) => [key, milliseconds(value)] as const)
const delays = namespace("transition-delay-").map(([key, value]) => [key, milliseconds(value)] as const)
const easings = namespace("ease-").map(([key, value]) => [key, easing(value)] as const)

if ([transitionProperties, durations, delays, easings, animations].some((list) => list.length === 0)) {
  fail("a motion scale in motion-tokens.css came out empty")
}

